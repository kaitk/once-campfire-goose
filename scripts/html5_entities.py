#!/usr/bin/env python3
"""Writes html5_entities.goose, the HTML5 named character references (html5.goose's tokenizer decodes
them as Nokogiri's HTML5 parser, gumbo, does), from Python's copy of the WHATWG table:

    python3 scripts/html5_entities.py > html5_entities.goose

Each entry is its name (with its ";", or without one for the legacy names that may omit it), a NUL,
and its characters in UTF-8; entries are sorted by name's bytes and H5_ENTITY_AT holds where each
starts, then the end.
"""
from html.entities import html5


def literal(data):
    out = []
    for b in data:
        if b in (0x22, 0x5C) or b < 0x20 or b >= 0x7F:
            out.append("\\x%02X" % b)
        else:
            out.append(chr(b))
    return "".join(out)


def main():
    names = sorted(html5, key=lambda name: name.encode())
    data, at = bytearray(), []
    for name in names:
        at.append(len(data))
        data += name.encode() + b"\0" + html5[name].encode()
    at.append(len(data))
    print("// Generated by scripts/html5_entities.py from the WHATWG named character references; don't edit.\n")
    print("namespace campfire;\n")
    print(f"let H5_ENTITY_COUNT = {len(names)};")
    print('let H5_ENTITY_DATA = "' + literal(data) + '";')
    numbers = ", ".join(str(a) for a in at)
    print(f"let H5_ENTITY_AT: i32[{len(at)}] = [{numbers}];")


if __name__ == "__main__":
    main()
